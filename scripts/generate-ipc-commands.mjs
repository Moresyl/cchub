import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");
const srcTauriDir = path.join(rootDir, "src-tauri", "src");
const libPath = path.join(srcTauriDir, "lib.rs");
const outputPath = path.join(rootDir, "docs", "IPC_COMMANDS.md");

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      return walk(fullPath);
    }
    return entry.isFile() && entry.name.endsWith(".rs") ? [fullPath] : [];
  });
}

function modulePathForFile(filePath) {
  const relative = path.relative(srcTauriDir, filePath).replaceAll(path.sep, "/");
  return relative
    .replace(/\.rs$/, "")
    .replace(/\/mod$/, "")
    .split("/")
    .join("::");
}

function compact(value) {
  return value.replace(/\s+/g, " ").trim();
}

function parseCommands() {
  const commandPattern = /#\[(?:tauri::)?command(?:\([^)]*\))?\]\s*(?:pub(?:\([^)]*\))?\s+)?(?:(async)\s+)?fn\s+([A-Za-z0-9_]+)\s*\(([\s\S]*?)\)\s*(?:->\s*([^{]+))?\{/g;
  return walk(srcTauriDir).flatMap((filePath) => {
    const content = fs.readFileSync(filePath, "utf8");
    const modulePath = modulePathForFile(filePath);
    return [...content.matchAll(commandPattern)].map((match) => ({
      name: match[2],
      modulePath,
      file: path.relative(rootDir, filePath).replaceAll(path.sep, "/"),
      async: Boolean(match[1]),
      params: compact(match[3] || ""),
      returnType: compact(match[4] || "()"),
    }));
  }).sort((a, b) => a.name.localeCompare(b.name) || a.modulePath.localeCompare(b.modulePath));
}

function parseRegisteredCommands() {
  const libContent = fs.readFileSync(libPath, "utf8");
  const block = libContent.match(/tauri::generate_handler!\[([\s\S]*?)\]\)/)?.[1] || "";
  return new Set(
    [...block.matchAll(/(?:[A-Za-z0-9_]+::)+([A-Za-z0-9_]+)\s*,/g)].map((match) => match[1]),
  );
}

function markdownEscape(value) {
  return value.replaceAll("|", "\\|");
}

const commands = parseCommands();
const registered = parseRegisteredCommands();
const registeredCommands = commands.filter((command) => registered.has(command.name));
const unregisteredCommands = commands.filter((command) => !registered.has(command.name));
const now = new Date().toISOString();

const lines = [
  "# IPC Commands",
  "",
  `Generated by \`node scripts/generate-ipc-commands.mjs\` at ${now}.`,
  "",
  "## Summary",
  "",
  `- Discovered commands: ${commands.length}`,
  `- Registered in \`tauri::generate_handler!\`: ${registeredCommands.length}`,
  `- Unregistered command functions: ${unregisteredCommands.length}`,
  "",
  "## Registered Commands",
  "",
  "| Command | Rust Module | Async | Parameters | Return | Source |",
  "|---|---|---:|---|---|---|",
  ...registeredCommands.map((command) => (
    `| \`${command.name}\` | \`${command.modulePath}\` | ${command.async ? "yes" : "no"} | \`${markdownEscape(command.params || "-")}\` | \`${markdownEscape(command.returnType)}\` | \`${command.file}\` |`
  )),
  "",
  "## Unregistered Command Functions",
  "",
  unregisteredCommands.length
    ? "| Command | Rust Module | Source |\n|---|---|---|\n"
      + unregisteredCommands.map((command) => (
        `| \`${command.name}\` | \`${command.modulePath}\` | \`${command.file}\` |`
      )).join("\n")
    : "None.",
  "",
];

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, `${lines.join("\n")}\n`);
console.log(`Generated ${path.relative(rootDir, outputPath)} with ${commands.length} commands.`);
